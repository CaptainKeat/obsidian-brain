"""Safe, dependency-free note operations for the Obsidian brain MCP.

This module deliberately does not import FastMCP, LanceDB, torch, or the RAG
indexer. It can be unit-tested with temporary directories and used while the
live indexer continues serving searches.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
import re
import shutil
import tempfile
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Mapping


DEFAULT_ROOTS = {
    "vault": Path(os.environ.get("VAULT_PATH", str(Path(__file__).resolve().parent / "examples" / "vault"))),
    "projects": Path(os.environ.get("PROJECTS_PATH", str(Path(__file__).resolve().parent / "examples" / "projects"))),
}

MEMORY_FOLDERS = {
    "fact": "Facts",
    "project-state": "Projects",
    "decision": "Decisions",
    "procedure": "Patterns",
    "incident": "Sessions",
    "worked-example": "Examples",
    "hypothesis": "Hypotheses",
    "preference": "Preferences",
    "gotcha": "Gotchas",
}

VALID_STATUSES = {"proposed", "observed", "verified", "stale", "superseded", "rejected"}
VALID_CONFIDENCE = {"low", "medium", "high"}
VALID_FEEDBACK = {"helpful", "stale", "wrong", "missing", "contradictory"}
_HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$", re.MULTILINE)


def _now() -> dt.datetime:
    return dt.datetime.now().astimezone()


def _slug(value: str, max_length: int = 80) -> str:
    value = re.sub(r"[^\w\s-]", "", value.lower()).strip()
    value = re.sub(r"[\s_]+", "-", value)
    return (value[:max_length] or "memory").strip("-")


def _hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _json_yaml(value: Any) -> str:
    """JSON is valid YAML and avoids hand-rolled escaping mistakes."""
    return json.dumps(value, ensure_ascii=False)


def _parse_scalar(value: str) -> Any:
    value = value.strip()
    if not value:
        return ""
    try:
        return json.loads(value)
    except json.JSONDecodeError:
        return value.strip("\"'")


def parse_frontmatter(text: str) -> tuple[dict[str, Any], str]:
    """Parse the simple top-level frontmatter used by the brain.

    Complex nested YAML is intentionally returned as plain text. Memory
    metadata generated by this module uses JSON-compatible scalars/lists.
    """
    if not text.startswith("---"):
        return {}, text
    match = re.match(r"^---\s*\r?\n(.*?)\r?\n---\s*\r?\n?", text, re.DOTALL)
    if not match:
        return {}, text
    metadata: dict[str, Any] = {}
    for line in match.group(1).splitlines():
        if not line.strip() or line.lstrip().startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        metadata[key.strip()] = _parse_scalar(value)
    return metadata, text[match.end():]


def _metadata_block(metadata: Mapping[str, Any]) -> str:
    lines = ["---"]
    for key, value in metadata.items():
        lines.append(f"{key}: {_json_yaml(value)}")
    lines.extend(["---", ""])
    return "\n".join(lines)


def resolve_note_path(
    path: str,
    root: str = "vault",
    roots: Mapping[str, Path] | None = None,
    *,
    must_exist: bool = True,
) -> Path:
    """Resolve a RAG-relative Markdown path without allowing root escape."""
    roots = roots or DEFAULT_ROOTS
    if root not in roots:
        raise ValueError(f"Unknown root {root!r}; expected one of {sorted(roots)}")
    if not path or "\x00" in path:
        raise ValueError("A non-empty note path is required")
    relative = Path(path.replace("\\", "/"))
    if relative.is_absolute() or any(part == ".." for part in relative.parts):
        raise ValueError("Absolute paths and parent traversal are not allowed")
    if relative.suffix.lower() != ".md":
        raise ValueError("Only Markdown notes can be accessed")
    base = Path(roots[root]).resolve()
    target = (base / relative).resolve()
    try:
        target.relative_to(base)
    except ValueError as exc:
        raise ValueError("Resolved path escapes the selected brain root") from exc
    if must_exist and not target.is_file():
        raise FileNotFoundError(f"Note not found in {root}: {path}")
    return target


def _parse_date(value: Any) -> dt.datetime | None:
    if not value:
        return None
    raw = str(value).strip()
    try:
        parsed = dt.datetime.fromisoformat(raw.replace("Z", "+00:00"))
        if parsed.tzinfo is None:
            parsed = parsed.replace(tzinfo=_now().tzinfo)
        return parsed
    except ValueError:
        try:
            return dt.datetime.strptime(raw[:10], "%Y-%m-%d").replace(tzinfo=_now().tzinfo)
        except ValueError:
            return None


def memory_warnings(metadata: Mapping[str, Any]) -> list[str]:
    warnings: list[str] = []
    status = str(metadata.get("status", "")).lower()
    if status in {"proposed", "hypothesis"}:
        warnings.append("unverified: treat as a hypothesis, not established fact")
    elif status in {"stale", "superseded", "rejected"}:
        warnings.append(f"status={status}: do not treat as current truth")
    valid_until = _parse_date(metadata.get("valid_until"))
    if valid_until and valid_until < _now():
        warnings.append(f"expired after {valid_until.date().isoformat()}")
    superseded_by = metadata.get("superseded_by")
    if superseded_by:
        warnings.append(f"superseded_by={superseded_by}")
    if status == "verified" and not metadata.get("sources") and not metadata.get("evidence"):
        warnings.append("verified status has no recorded source/evidence")
    return warnings


def _extract_section(body: str, section: str) -> str:
    wanted = section.strip().lower()
    if not wanted:
        return body
    matches = list(_HEADING.finditer(body))
    for index, match in enumerate(matches):
        title = match.group(2).strip().lower()
        if title != wanted and wanted not in title:
            continue
        level = len(match.group(1))
        end = len(body)
        for later in matches[index + 1:]:
            if len(later.group(1)) <= level:
                end = later.start()
                break
        return body[match.start():end].strip()
    raise KeyError(f"Section not found: {section}")


def note_info(
    path: str,
    root: str = "vault",
    roots: Mapping[str, Path] | None = None,
) -> dict[str, Any]:
    target = resolve_note_path(path, root, roots)
    text = target.read_text(encoding="utf-8")
    metadata, body = parse_frontmatter(text)
    stat = target.stat()
    return {
        "root": root,
        "path": path.replace("\\", "/"),
        "absolute_path": str(target),
        "sha256": _hash(text),
        "size_bytes": stat.st_size,
        "modified_at": dt.datetime.fromtimestamp(stat.st_mtime, tz=_now().tzinfo).isoformat(),
        "metadata": metadata,
        "warnings": memory_warnings(metadata),
        "body_chars": len(body),
    }


def read_note(
    path: str,
    root: str = "vault",
    section: str = "",
    max_chars: int = 16000,
    roots: Mapping[str, Path] | None = None,
) -> dict[str, Any]:
    if max_chars < 500 or max_chars > 100_000:
        raise ValueError("max_chars must be between 500 and 100000")
    target = resolve_note_path(path, root, roots)
    text = target.read_text(encoding="utf-8")
    metadata, body = parse_frontmatter(text)
    selected = _extract_section(body, section) if section else body
    truncated = len(selected) > max_chars
    selected = selected[:max_chars]
    info = note_info(path, root, roots)
    info.update({"section": section or None, "truncated": truncated, "content": selected})
    return info


def _atomic_write(target: Path, content: str) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=f".{target.stem}-", suffix=".tmp", dir=target.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_name, target)
    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise



@contextmanager
def _note_lock(target):
    """Serialize cooperating MCP processes across read/check/write operations."""
    target.parent.mkdir(parents=True, exist_ok=True)
    lock_path = target.with_suffix(target.suffix + ".lock")
    with open(lock_path, "a+b") as handle:
        handle.seek(0, 2)
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        if os.name == "nt":
            import msvcrt
            msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
        else:
            import fcntl
            fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def _replace_metadata(text, updates):
    """Update selected top-level YAML fields while retaining unrelated raw YAML."""
    match = re.match(r"^---[^\S\n]*\n(.*?)\n---[^\S\n]*\n?", text, re.DOTALL)
    if not match:
        return _metadata_block(updates) + text
    lines = match.group(1).splitlines(keepends=True)
    kept = []
    skipping = False
    for line in lines:
        field = re.match(r"^([A-Za-z_][\w-]*):", line)
        if field:
            skipping = field.group(1) in updates
        elif line.strip() and not line[0].isspace() and not line.startswith("#"):
            skipping = False
        if not skipping:
            kept.append(line)
    header = "".join(kept).rstrip() + "\n"
    header += "\n".join(f"{key}: {_json_yaml(value)}" for key, value in updates.items())
    return "---\n" + header + "\n---\n" + text[match.end():]


def update_note(
    path: str,
    body: str,
    *,
    root: str = "vault",
    mode: str = "append",
    heading: str = "Update",
    expected_sha256: str = "",
    roots: Mapping[str, Path] | None = None,
) -> dict[str, Any]:
    """Safely append to or replace a vault note body.

    Replacement requires the caller to supply the hash returned by read_note,
    preventing stale-context overwrites. Every replacement creates a .bak file
    that the Markdown indexer ignores.
    """
    if root != "vault":
        raise ValueError("Project documents are read-only through the brain MCP")
    if not body.strip():
        raise ValueError("Update body cannot be empty")
    if len(body) > 200_000:
        raise ValueError("Update body is too large")
    if mode not in {"append", "replace_body"}:
        raise ValueError("mode must be append or replace_body")
    target = resolve_note_path(path, root, roots)
    with _note_lock(target):
        original = target.read_text(encoding="utf-8")
        original_hash = _hash(original)
        if expected_sha256 and expected_sha256 != original_hash:
            raise RuntimeError("Note changed since it was read; fetch it again before updating")
        metadata, old_body = parse_frontmatter(original)
        if mode == "replace_body":
            if not expected_sha256:
                raise ValueError("replace_body requires expected_sha256 from obsidian_get_note")
            stamp = _now().strftime("%Y%m%d-%H%M%S-%f")
            backup = target.with_suffix(target.suffix + f".bak-{stamp}")
            shutil.copy2(target, backup)
            # Preserve arbitrary original YAML, including nested fields/comments.
            prefix = original[:len(original) - len(old_body)]
            new_text = prefix + body.strip() + "\n"
        else:
            backup = None
            label = re.sub(r"[\r\n#]+", " ", heading).strip() or "Update"
            new_text = original.rstrip() + f"\n\n## {label} — {_now().isoformat(timespec='seconds')}\n\n{body.strip()}\n"
        if _hash(target.read_text(encoding="utf-8")) != original_hash:
            raise RuntimeError("Note changed while updating; fetch it again before updating")
        _atomic_write(target, new_text)
        result = note_info(path, root, roots)
        result.update({"mode": mode, "previous_sha256": original_hash, "backup": str(backup) if backup else None})
        return result


def save_memory(
    title: str, body: str, *, memory_type: str,
    status: str | None = None, confidence: str | None = None,
    project: str | None = None, evidence: str | None = None,
    applies_when: str | None = None, sources: list[str] | None = None,
    tags: list[str] | None = None, valid_until: str | None = None,
    supersedes: list[str] | None = None, expected_sha256: str = "",
    roots: Mapping[str, Path] | None = None,
) -> dict[str, Any]:
    """Revise current metadata while preserving history; None preserves, empty clears.

    Revisions require the hash returned by read_note. No automatic historical
    note rewrite or reverse-link mutation occurs.
    """
    roots = roots or DEFAULT_ROOTS
    if memory_type not in MEMORY_FOLDERS:
        raise ValueError(f"Unknown memory_type; expected one of {sorted(MEMORY_FOLDERS)}")
    if not title.strip() or not body.strip():
        raise ValueError("Memory title and body are required")
    if len(body) > 200_000:
        raise ValueError("Memory body is too large")
    if valid_until and not _parse_date(valid_until):
        raise ValueError("valid_until must be an ISO date or datetime")
    relative = Path("Cowork") / MEMORY_FOLDERS[memory_type] / f"{_slug(title)}.md"
    target = resolve_note_path(str(relative), "vault", roots, must_exist=False)
    with _note_lock(target):
        original = target.read_text(encoding="utf-8") if target.exists() else ""
        old, _ = parse_frontmatter(original)
        if original:
            if not expected_sha256:
                raise ValueError("Revising an existing memory requires expected_sha256 from obsidian_get_note")
            if expected_sha256 != _hash(original):
                raise RuntimeError("Note changed since it was read; fetch it again before saving")
            if old.get("title") != title.strip() or old.get("type") != memory_type:
                raise ValueError("Memory filename collision; choose a distinct title")
        elif expected_sha256:
            raise RuntimeError("Expected an existing memory, but it no longer exists")
        actual_status = status if status is not None else old.get("status", "verified")
        actual_confidence = confidence if confidence is not None else old.get("confidence", "medium")
        if actual_status not in VALID_STATUSES:
            raise ValueError(f"Unknown status; expected one of {sorted(VALID_STATUSES)}")
        if actual_confidence not in VALID_CONFIDENCE:
            raise ValueError(f"Unknown confidence; expected one of {sorted(VALID_CONFIDENCE)}")
        if actual_status == "verified" and not ((evidence or "").strip() or sources):
            raise ValueError("Verified memories require fresh evidence or at least one source")
        now = _now().isoformat(timespec="seconds")
        metadata = {"title": title.strip(), "type": memory_type,
                    "status": actual_status, "confidence": actual_confidence,
                    "updated_at": now,
                    "verified_at": now if actual_status == "verified" else ""}
        optional = {"project": project, "evidence": evidence, "applies_when": applies_when,
                    "sources": sources, "tags": tags, "valid_until": valid_until,
                    "supersedes": supersedes}
        for key, value in optional.items():
            if value is not None:
                metadata[key] = value.strip() if isinstance(value, str) else value
            elif not original:
                metadata[key] = [] if key in {"sources", "tags", "supersedes"} else ""
        if not original or tags is not None:
            metadata["tags"] = sorted(set(["cowork", memory_type] + (tags or [])))
        backup = None
        if original:
            backup = target.with_suffix(target.suffix + ".bak-" + _now().strftime("%Y%m%d-%H%M%S-%f"))
            shutil.copy2(target, backup)
            content = _replace_metadata(original, metadata).rstrip()
            content += f"\n\n## Revision — {now}\n\n{body.strip()}\n"
            content += "\nRevision metadata: " + json.dumps(metadata, ensure_ascii=False) + "\n"
        else:
            metadata.update({"created": now, "source": "cowork"})
            content = _metadata_block(metadata) + f"# {title.strip()}\n\n## Lesson\n\n{body.strip()}\n"
            if applies_when:
                content += f"\n## Applies when\n\n{applies_when.strip()}\n"
            if evidence:
                content += f"\n## Evidence\n\n{evidence.strip()}\n"
            if sources:
                content += "\n## Sources\n\n" + "\n".join(f"- {source}" for source in sources) + "\n"
        # Recheck after preparing the content to catch non-cooperating editor writes.
        if original and _hash(target.read_text(encoding="utf-8")) != _hash(original):
            raise RuntimeError("Note changed while saving; fetch it again before saving")
        _atomic_write(target, content)
        result = note_info(str(relative), "vault", roots)
        result.update({"previous_sha256": _hash(original) if original else None,
                       "backup": str(backup) if backup else None})
        return result



def record_feedback(
    target_path: str,
    outcome: str,
    detail: str,
    *,
    query: str = "",
    roots: Mapping[str, Path] | None = None,
) -> dict[str, Any]:
    if outcome not in VALID_FEEDBACK:
        raise ValueError(f"Unknown outcome; expected one of {sorted(VALID_FEEDBACK)}")
    if not detail.strip():
        raise ValueError("Feedback detail is required")
    roots = roots or DEFAULT_ROOTS
    date = _now().date().isoformat()
    relative = Path("Cowork") / "Feedback" / f"{date}-brain-feedback.md"
    target = resolve_note_path(str(relative), "vault", roots, must_exist=False)
    entry = (
        f"## {_now().isoformat(timespec='seconds')} — {outcome}\n\n"
        f"- Target: `{target_path}`\n"
        f"- Query: {query or '(not recorded)'}\n"
        f"- Outcome: {outcome}\n\n"
        f"{detail.strip()}\n"
    )
    if target.exists():
        return update_note(str(relative), entry, root="vault", mode="append",
                           heading="Feedback", roots=roots)
    metadata = {
        "title": f"Brain retrieval feedback {date}",
        "type": "feedback",
        "status": "observed",
        "created": _now().isoformat(timespec="seconds"),
        "source": "cowork",
        "tags": ["cowork", "brain-feedback"],
    }
    _atomic_write(target, _metadata_block(metadata) + f"# Brain retrieval feedback — {date}\n\n{entry}")
    return note_info(str(relative), "vault", roots)


def compact_metadata(info: Mapping[str, Any]) -> str:
    metadata = info.get("metadata") or {}
    fields = []
    for key in ("type", "status", "confidence", "project", "verified_at", "valid_until"):
        value = metadata.get(key)
        if value:
            fields.append(f"{key}={value}")
    if info.get("warnings"):
        fields.append("warning=" + " | ".join(info["warnings"]))
    return "; ".join(fields)
